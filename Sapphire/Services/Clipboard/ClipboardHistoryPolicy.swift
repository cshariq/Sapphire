// MARK: - Retention

nonisolated enum ClipboardHistoryBudget {
    static let defaultItemLimit = 200
    static let defaultStorageLimitMB = 512
    static let itemLimitRange = 10...2000
    static let storageLimitRangeMB = 64...4096

    static func retained(_ items: [ClipboardItem], maxItems: Int?, maxBytes: Int?) -> [ClipboardItem] {
        guard maxItems != nil || maxBytes != nil else { return items }
        var kept: [ClipboardItem] = []
        kept.reserveCapacity(min(items.count, (maxItems ?? items.count) + 16))
        var count = 0
        var bytes = 0
        for item in items {
            if item.isPinned {
                kept.append(item)
                continue
            }
            if let maxItems, count >= maxItems { continue }
            let size = max(0, item.byteSize)
            if let maxBytes, count > 0, bytes + size > maxBytes { continue }
            kept.append(item)
            count += 1
            bytes += size
        }
        return kept
    }
}

nonisolated enum ClipboardTextLimit {
    static let maxUTF8Bytes = 1_000_000

    static func truncated(_ text: String, maxUTF8Bytes: Int = maxUTF8Bytes) -> (text: String, wasTruncated: Bool) {
        guard text.utf8.count > maxUTF8Bytes else { return (text, false) }
        var used = 0
        var end = text.startIndex
        for index in text.indices {
            let next = text.index(after: index)
            let width = text.utf8.distance(from: index, to: next)
            guard used + width <= maxUTF8Bytes else { break }
            used += width
            end = next
        }
        return (String(text[..<end]), true)
    }
}

// MARK: - Capture filtering

nonisolated enum ClipboardCaptureFilter {
    static let concealedType = "org.nspasteboard.ConcealedType"
    static let transientType = "org.nspasteboard.TransientType"
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    static let sourceType = "org.nspasteboard.source"

    static func shouldIgnore(
        types: Set<String>,
        sourceBundleID: String?,
        frontmostBundleID: String?,
        ignoredBundleIDs: Set<String>,
        ignoreMarkedItems: Bool
    ) -> Bool {
        if types.contains(transientType) { return true }
        if ignoreMarkedItems, types.contains(concealedType) || types.contains(autoGeneratedType) {
            return true
        }
        guard !ignoredBundleIDs.isEmpty else { return false }
        let lowered = Set(ignoredBundleIDs.map { $0.lowercased() })
        if let sourceBundleID, lowered.contains(sourceBundleID.lowercased()) { return true }
        if let frontmostBundleID, lowered.contains(frontmostBundleID.lowercased()) { return true }
        return false
    }
}

