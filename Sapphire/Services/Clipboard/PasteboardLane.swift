import AppKit

nonisolated final class PasteboardLane: @unchecked Sendable {
    static let shared = PasteboardLane()

    private let queue = DispatchQueue(label: "com.sapphire.pasteboard.lane", qos: .userInitiated)
    private let lock = NSLock()
    private var outstanding = 0

    private init() {}

    var isBusy: Bool {
        lock.lock(); defer { lock.unlock() }
        return outstanding > 0
    }

    func run<T>(
        timeout: TimeInterval = 2,
        _ work: @escaping (NSPasteboard) -> T?,
        completion: @escaping @MainActor (T?) -> Void,
        didFinish: (@MainActor () -> Void)? = nil
    ) {
        let delivery = LaneDelivery(completion)
        lock.lock(); outstanding += 1; lock.unlock()

        let deadline = DispatchWorkItem { delivery.deliver(nil) }
        DispatchQueue.main.asyncAfter(deadline: .now() + timeout, execute: deadline)

        queue.async { [self] in
            let value = work(NSPasteboard.general)
            lock.lock(); outstanding -= 1; lock.unlock()
            let box = UncheckedBox(value)
            DispatchQueue.main.async {
                deadline.cancel()
                MainActor.assumeIsolated {
                    delivery.deliver(box.value)
                    didFinish?()
                }
            }
        }
    }

    func perform(_ work: @escaping (NSPasteboard) -> Void) {
        lock.lock(); outstanding += 1; lock.unlock()
        queue.async { [self] in
            work(NSPasteboard.general)
            lock.lock(); outstanding -= 1; lock.unlock()
        }
    }

    func write(
        _ work: @escaping (NSPasteboard) -> Bool,
        completion: (@MainActor (_ changeCount: Int?) -> Void)? = nil
    ) {
        run(timeout: 5, { pasteboard -> Int? in
            work(pasteboard) ? pasteboard.changeCount : nil
        }, completion: { changeCount in
            completion?(changeCount)
        })
    }
}

private final class LaneDelivery<T>: @unchecked Sendable {
    private var completion: (@MainActor (T?) -> Void)?

    init(_ completion: @escaping @MainActor (T?) -> Void) {
        self.completion = completion
    }

    func deliver(_ value: T?) {
        dispatchPrecondition(condition: .onQueue(.main))
        let callback = completion
        completion = nil
        guard let callback else { return }
        MainActor.assumeIsolated { callback(value) }
    }
}

private struct UncheckedBox<T>: @unchecked Sendable {
    let value: T?
    init(_ value: T?) { self.value = value }
}

extension NSPasteboard.PasteboardType {
    static let sapphireConcealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let sapphireTransient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let sapphireAutoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let sapphireSource = NSPasteboard.PasteboardType("org.nspasteboard.source")
}