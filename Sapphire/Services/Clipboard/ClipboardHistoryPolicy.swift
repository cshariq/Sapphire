// MARK: - Search

nonisolated enum ClipboardSearch {
    static func normalizedQuery(_ query: String) -> String {
        query.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    static func matches(_ item: ClipboardItem, query: String) -> Bool {
        let options: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive]
        if item.preview.range(of: query, options: options) != nil { return true }
        if let path = item.fileURLString, path.range(of: query, options: options) != nil { return true }
        if let text = item.textContent, text.range(of: query, options: options) != nil { return true }
        return false
    }

    static func filter(_ items: [ClipboardItem], kinds: Set<ClipboardItemKind>?, query: String) -> [ClipboardItem] {
        let query = normalizedQuery(query)
        return items.filter { item in
            if let kinds, !kinds.contains(item.kind) { return false }
            return query.isEmpty || matches(item, query: query)
        }
    }
}

nonisolated struct ClipboardSearchCache {
    private struct Key: Equatable {
        let revision: Int
        let kinds: Set<ClipboardItemKind>?
        let query: String
    }

    private var key: Key?
    private var results: [ClipboardItem] = []
    private(set) var fullScans = 0

    mutating func results(
        for items: [ClipboardItem],
        revision: Int,
        kinds: Set<ClipboardItemKind>?,
        query rawQuery: String
    ) -> [ClipboardItem] {
        let query = ClipboardSearch.normalizedQuery(rawQuery)
        let next = Key(revision: revision, kinds: kinds, query: query)
        if next == key { return results }

        let source: [ClipboardItem]
        if let key, key.revision == revision, key.kinds == kinds,
           !key.query.isEmpty, query.count > key.query.count,
           query.lowercased().hasPrefix(key.query.lowercased()) {
            source = results
        } else {
            source = items
            fullScans += 1
        }
        results = ClipboardSearch.filter(source, kinds: kinds, query: query)
        key = next
        return results
    }
}

@MainActor
final class ClipboardSearchModel: ObservableObject {
    @Published private(set) var results: [ClipboardItem] = []

    private let queue = DispatchQueue(label: "com.sapphire.clipboard.search", qos: .userInitiated)
    private nonisolated(unsafe) var cache = ClipboardSearchCache()
    private var generation = 0
    private var pending: DispatchWorkItem?

    func update(items: [ClipboardItem], revision: Int, kinds: Set<ClipboardItemKind>?, query: String, debounce: Bool) {
        generation += 1
        let token = generation
        pending?.cancel()
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            self.queue.async {
                let found = self.cache.results(for: items, revision: revision, kinds: kinds, query: query)
                DispatchQueue.main.async {
                    MainActor.assumeIsolated {
                        guard self.generation == token else { return }
                        if self.results != found { self.results = found }
                    }
                }
            }
        }
        pending = work
        let trimmed = ClipboardSearch.normalizedQuery(query)
        if debounce, !trimmed.isEmpty {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.08, execute: work)
        } else {
            DispatchQueue.main.async(execute: work)
        }
    }
}

// MARK: - Multi-item paste

nonisolated enum ClipboardMultiPaste {
    enum Entry: Equatable {
        case text(String)
        case image(id: String)
        case file(path: String)
    }

    enum Plan: Equatable {
        case joinedText(String)
        case items([Entry])
    }

    static func plan(for items: [ClipboardItem]) -> Plan? {
        guard !items.isEmpty else { return nil }
        if items.allSatisfy({ $0.kind == .text }) {
            return .joinedText(items.map { $0.textContent ?? $0.preview }.joined(separator: "\n"))
        }
        let entries: [Entry] = items.compactMap { item in
            switch item.kind {
            case .text: return .text(item.textContent ?? item.preview)
            case .image: return .image(id: item.id)
            case .file, .folder: return item.fileURLString.map { .file(path: $0) }
            }
        }
        return entries.isEmpty ? nil : .items(entries)
    }
}